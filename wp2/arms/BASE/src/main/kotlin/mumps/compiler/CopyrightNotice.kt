    fun sysout(s: String) = out.write(s)

    sysout("// ==============================================================\n")
    sysout("//#+ This module generated by Mumps Compiler \n")
    // C: time(&curtime); fprintf(Out, "//#+ %s", ctime(&curtime));
    // ctime() emits a fixed C-locale local-time string with a trailing newline.
