package mumps.compiler

import java.io.Writer
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

/**
 * Kotlin translation of compiler-copyright-notice.c::copyright_notice
 * (Study Subset unit 1, Batch 1, arm BASE; translated 2026-11-14).
 *
 * Emits the standard generated-module header: banner lines plus the
 * "//#+ <ctime>" timestamp line. Byte-exact with the C original except
 * the timestamp value itself.
 */
